"use strict";

const { CHART_TYPE_META } = require("./chart-config");

const BADGE_STYLE = "flat-square";
const BADGE_CACHE_SECONDS = "900";

function formatNumber(value) {
  return Number(value).toLocaleString("en-US");
}

function buildRawBaseUrl(owner, repo, outputBranch, outputPath) {
  const dir = outputPath.includes("/") ? outputPath.slice(0, outputPath.lastIndexOf("/")) : "";
  const prefix = dir.length > 0 ? `/${dir}` : "";
  return `https://raw.githubusercontent.com/${owner}/${repo}/${outputBranch}${prefix}`;
}

function buildJsonBadgeUrl({ owner, repo, outputBranch, outputPath, query, label, color }) {
  const source = `https://raw.githubusercontent.com/${owner}/${repo}/${outputBranch}/${outputPath}`;
  const url = encodeURIComponent(source);
  const queryText = encodeURIComponent(query);
  const labelText = encodeURIComponent(label);
  return `https://img.shields.io/badge/dynamic/json?url=${url}&query=${queryText}&label=${labelText}&color=${color}&style=${BADGE_STYLE}&logo=curseforge&cacheSeconds=${BADGE_CACHE_SECONDS}`;
}

function buildBadgeLines(inputs) {
  const common = {
    owner: inputs.owner,
    repo: inputs.repo,
    outputBranch: inputs.outputBranch,
    outputPath: inputs.outputPath,
  };
  const definitions = [
    ["downloads/total", "$.stats.total", "0A7EA4"],
    ["downloads/day", "$.stats.day", "1E8E3E"],
    ["downloads/week", "$.stats.week", "0069C2"],
    ["downloads/month", "$.stats.month", "B26A00"],
    ["downloads/year", "$.stats.year", "6A1B9A"],
  ];
  return definitions.map(
    ([label, query, color]) =>
      `[![${label}](${buildJsonBadgeUrl({ ...common, query, label, color })})](${buildRawBaseUrl(inputs.owner, inputs.repo, inputs.outputBranch, inputs.outputPath)}/${inputs.outputPath.split("/").pop()})`,
  );
}

function buildRawRootUrl(inputs) {
  return `https://raw.githubusercontent.com/${inputs.owner}/${inputs.repo}/${inputs.outputBranch}`;
}

function buildChartSection(inputs) {
  if (!inputs.publishChart) return null;

  const root = buildRawRootUrl(inputs);
  const primaryType = inputs.chartTypes[0];
  const primaryTheme = inputs.chartThemes[0];
  const lines = [
    "## Total downloads trend",
    "",
    `![Downloads ${primaryType} ${primaryTheme}](${root}/${inputs.chartOutputPath})`,
  ];

  if (inputs.chartTypes.length * inputs.chartThemes.length > 1) {
    lines.push(
      "",
      "## All charts",
      "",
      "Charts are generated on the first run. Customize them freely; only the data tables below are updated on later runs.",
    );
    for (const chartType of inputs.chartTypes) {
      for (const chartTheme of inputs.chartThemes) {
        const meta = CHART_TYPE_META[chartType];
        const description = meta ? meta.latestLabel : chartType;
        lines.push(
          "",
          `### ${chartType}`,
          "",
          `![${description} ${chartTheme}](${root}/${inputs.chartsOutputDir}/${chartType}--${chartTheme}.svg)`,
        );
      }
    }
  }

  return lines;
}

function buildDashboardMarkdown({ inputs, payload }) {
  const repoLabel = `${inputs.owner}/${inputs.repo}`;
  const partialLabels = [];
  if (payload.partial.day) partialLabels.push("day");
  if (payload.partial.week) partialLabels.push("week");
  if (payload.partial.month) partialLabels.push("month");
  if (payload.partial.year) partialLabels.push("year");
  const partialText = partialLabels.length > 0 ? partialLabels.join(", ") : "none";

  const lines = [
    `# ${repoLabel} downloads`,
    "",
    ...buildBadgeLines(inputs),
    "",
    `CurseForge mod \`${inputs.curseforgeModId}\`, tracked by [curseforge-downloads-action](https://github.com/N6REJ/curseforge-downloads-action).`,
    "",
  ];

  const chartSection = buildChartSection(inputs);
  if (chartSection) {
    lines.push(...chartSection, "");
  }

  lines.push(
    "## Data",
    "",
    "| Metric | Value |",
    "|---|---|",
    `| Total | ${formatNumber(payload.stats.total)} |`,
    `| Day | ${formatNumber(payload.stats.day)}${payload.partial.day ? " (partial)" : ""} |`,
    `| Week | ${formatNumber(payload.stats.week)}${payload.partial.week ? " (partial)" : ""} |`,
    `| Month | ${formatNumber(payload.stats.month)}${payload.partial.month ? " (partial)" : ""} |`,
    `| Year | ${formatNumber(payload.stats.year)}${payload.partial.year ? " (partial)" : ""} |`,
    "",
    "| Field | Value |",
    "|---|---|",
    `| Repository | \`${repoLabel}\` |`,
    `| CurseForge mod id | \`${inputs.curseforgeModId}\` |`,
    `| Update mode | ${payload.profile.hourlyEnabled ? "hourly" : "daily"} |`,
    `| Window | ${payload.snapshots.windowDays} days |`,
    `| Snapshots | ${payload.snapshots.count} |`,
    `| Partial | ${partialText} |`,
    `| Generated at | \`${payload.generatedAt}\` |`,
    "",
    `Source data: [\`${inputs.outputPath}\`](${buildRawBaseUrl(inputs.owner, inputs.repo, inputs.outputBranch, inputs.outputPath)}/${inputs.outputPath.split("/").pop()})`,
    "",
    "<sub>Generated by <a href=\"https://github.com/N6REJ/curseforge-downloads-action\">curseforge-downloads-action</a></sub>",
    "",
  );

  return lines.join("\n");
}

const WINDOW_MARKER = "| Window |";

function hasWindowRow(content) {
  return typeof content === "string" && content.includes(WINDOW_MARKER);
}

function splitLines(content) {
  const normalized = content.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
  const trailingNewline = normalized.endsWith("\n");
  const lines = normalized.split("\n");
  if (trailingNewline) lines.pop();
  return { lines, trailingNewline };
}

function isTableRow(line) {
  return typeof line === "string" && line.trimStart().startsWith("|");
}

function replaceTable(lines, headerLine, replacement) {
  const index = lines.findIndex((line) => line.trim() === headerLine.trim());
  if (index === -1) return false;

  let end = index + 1;
  if (end < lines.length && /^\|[\s:|-]+\|$/.test(lines[end].trim())) {
    end += 1;
  }
  while (end < lines.length && isTableRow(lines[end])) {
    end += 1;
  }

  lines.splice(index, end - index, ...replacement);
  return true;
}

function buildMetricTable(payload) {
  return [
    "| Metric | Value |",
    "|---|---|",
    `| Total | ${formatNumber(payload.stats.total)} |`,
    `| Day | ${formatNumber(payload.stats.day)}${payload.partial.day ? " (partial)" : ""} |`,
    `| Week | ${formatNumber(payload.stats.week)}${payload.partial.week ? " (partial)" : ""} |`,
    `| Month | ${formatNumber(payload.stats.month)}${payload.partial.month ? " (partial)" : ""} |`,
    `| Year | ${formatNumber(payload.stats.year)}${payload.partial.year ? " (partial)" : ""} |`,
  ];
}

function buildFieldTable(inputs, payload) {
  const partialLabels = [];
  if (payload.partial.day) partialLabels.push("day");
  if (payload.partial.week) partialLabels.push("week");
  if (payload.partial.month) partialLabels.push("month");
  if (payload.partial.year) partialLabels.push("year");
  const partialText = partialLabels.length > 0 ? partialLabels.join(", ") : "none";

  return [
    "| Field | Value |",
    "|---|---|",
    `| Repository | \`${inputs.owner}/${inputs.repo}\` |`,
    `| CurseForge mod id | \`${inputs.curseforgeModId}\` |`,
    `| Update mode | ${payload.profile.hourlyEnabled ? "hourly" : "daily"} |`,
    `| Window | ${payload.snapshots.windowDays} days |`,
    `| Snapshots | ${payload.snapshots.count} |`,
    `| Partial | ${partialText} |`,
    `| Generated at | \`${payload.generatedAt}\` |`,
  ];
}

function refreshDashboardData(existingContent, { inputs, payload }) {
  if (existingContent == null) {
    return buildDashboardMarkdown({ inputs, payload });
  }

  const { lines, trailingNewline } = splitLines(existingContent);
  const changedMetric = replaceTable(lines, "| Metric | Value |", buildMetricTable(payload));
  const changedField = replaceTable(lines, "| Field | Value |", buildFieldTable(inputs, payload));

  if (!changedMetric && !changedField) {
    return existingContent;
  }

  const result = lines.join("\n");
  return trailingNewline ? `${result}\n` : result;
}

module.exports = {
  buildDashboardMarkdown,
  refreshDashboardData,
  hasWindowRow,
  WINDOW_MARKER,
};
